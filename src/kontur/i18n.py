def language_codes() -> tuple[str, ...]:
    return _LANGS


def set_language(code: str) -> str:
    global _current
    _current = code if code in _TEXT else "pl"
    return _current


def get_language() -> str:
    return _current


def t(key: str) -> str:
    table = _TEXT.get(_current) or _TEXT["pl"]
    if key in table:
        return table[key]
    return _TEXT["pl"].get(key, key)


def tf(key: str, **values: object) -> str:
    return t(key).format(**values)


def message_keys() -> tuple[str, ...]:
    return tuple(_TEXT["pl"])
